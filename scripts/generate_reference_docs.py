"""Generates docs/DATABASE_SCHEMA.md (tables section) and docs/API_DOCUMENTATION.md (endpoint index) from the code."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
import app.models  # noqa
from app.core.db import Base  # noqa

DOMAINS = {
    "Identity & tenancy": ["users", "user_sessions", "auth_tokens", "oauth_accounts", "organizations", "memberships", "invitations", "workspaces"],
    "Assistant": ["conversations", "conversation_shares", "messages"],
    "Knowledge / RAG": ["documents", "document_versions", "document_chunks"],
    "Agents & approvals": ["agents", "agent_runs", "agent_run_steps", "approvals"],
    "Workflows": ["workflows", "workflow_versions", "workflow_executions", "workflow_execution_logs", "form_submissions", "records"],
    "Data intelligence": ["datasets", "dataset_queries"],
    "Tasks": ["tasks", "task_comments", "task_attachments", "task_activity"],
    "Billing & usage": ["subscriptions", "invoices", "usage_counters"],
    "AI ledger & caching": ["ai_requests", "ai_response_cache"],
    "Platform": ["jobs", "notifications", "notification_preferences", "email_outbox", "integration_connections", "integration_logs",
                 "feature_flags", "support_tickets", "experiment_assignments", "eval_runs", "audit_logs", "analytics_events"],
}
lines = []
tables = Base.metadata.tables
for dom, names in DOMAINS.items():
    lines.append(f"\n### {dom}\n")
    for n in names:
        t = tables[n]
        tenant = "org_id" in t.c and not t.c.org_id.nullable
        lines.append(f"**`{n}`**{' — tenant-scoped (`org_id NOT NULL`)' if tenant else ''}\n")
        lines.append("| Column | Type | Null | Notes |\n|---|---|---|---|")
        for c in t.columns:
            notes = []
            if c.primary_key:
                notes.append("PK")
            for fk in c.foreign_keys:
                notes.append(f"FK → {fk.target_fullname} ({fk.ondelete or 'NO ACTION'})")
            if c.unique:
                notes.append("unique")
            if c.index:
                notes.append("indexed")
            if c.computed is not None:
                notes.append("generated")
            try:
                typ = str(c.type)
            except Exception:
                typ = c.type.__class__.__name__
            lines.append(f"| {c.name} | {typ} | {'yes' if c.nullable else 'no'} | {', '.join(notes)} |")
        lines.append("")
covered = {n for v in DOMAINS.values() for n in v}
missing = set(tables) - covered
assert not missing, missing
schema = (ROOT / "docs" / "DATABASE_SCHEMA.md")
head = schema.read_text().split("<!-- GENERATED -->")[0] if schema.exists() else ""
schema.write_text(head + "<!-- GENERATED -->\n## Table reference (generated by `scripts/generate_reference_docs.py`)\n" + "\n".join(lines))

spec = json.loads((ROOT / "docs" / "openapi.json").read_text())
api = (ROOT / "docs" / "API_DOCUMENTATION.md")
head = api.read_text().split("<!-- GENERATED -->")[0] if api.exists() else ""
by_tag = {}
for path, ops in spec["paths"].items():
    for method, op in ops.items():
        by_tag.setdefault((op.get("tags") or ["other"])[0], []).append((method.upper(), path, op.get("summary", "")))
out = ["<!-- GENERATED -->", "## Endpoint index (generated from OpenAPI)", ""]
for tag in sorted(by_tag):
    out.append(f"### {tag}\n\n| Method | Path | Summary |\n|---|---|---|")
    for m, p, s in sorted(by_tag[tag], key=lambda x: (x[1], x[0])):
        out.append(f"| {m} | `{p}` | {s} |")
    out.append("")
api.write_text(head + "\n".join(out))
print(len(tables), "tables;", sum(len(v) for v in by_tag.values()), "operations")
